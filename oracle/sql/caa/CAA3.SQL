CREATE OR REPLACE FUNCTION TP756_NAIYO (
	  w_BKNCD	VARCHAR2	default null		-- 物件コード
	, w_AREA	VARCHAR2	default null		-- エリア
	, w_PWBS	VARCHAR2	default null		-- PWBS
	, w_SUB		VARCHAR2	default null		-- SUB
) RETURN VARCHAR2 IS

	p_sedai_cnt	number;				-- 世代件数
	p_data_cnt	number;				-- 一意データ件数
	p_dyset_m	varchar2(2);			-- 作成日（mm）
	p_dyset_d	varchar2(2);			-- 作成日（dd）

	p_naiyo		varchar2(10) := null;	-- 作業内容
	p_sedai		TP756.SEDAI%type;		-- 世代番号
	p_sedai_b	TP756.SEDAI%type;		-- 世代番号(前)
	p_kubun		TP756.KUBUN%type;		-- 新規改造区分
	p_kubun_b	TP756.KUBUN%type;		-- 新規改造区分(前)
	p_siyo		TP756.SIYO%type;		-- 仕様
	p_siyo_b	TP756.SIYO%type;		-- 仕様(前)
	p_dyset		TP756.DYSET%TYPE;		-- 作成日時
	p_dyset_b	TP756.DYSET%TYPE;		-- 作成日時(前)
	i INT := 0;

BEGIN
	FOR vRec IN
	  ( SELECT *
	      FROM TP756
	      WHERE BKNCD = w_BKNCD
	        AND AREA = w_AREA
	        AND PWBS = w_PWBS
	        AND SUB = w_SUB
	      ORDER BY SEDAI )
	LOOP
		i := i + 1;
		IF i = 1 THEN
			p_sedai_b := vRec.SEDAI;
			p_kubun_b := vRec.KUBUN;
			p_siyo_b := vRec.SIYO;
			p_dyset_b := vRec.DYSET;
		ELSE
			p_sedai := vRec.SEDAI;
			p_kubun := vRec.KUBUN;
			p_siyo := vRec.SIYO;
			p_dyset := vRec.DYSET;
		END IF;
	END LOOP;

	IF i = 1 THEN
		-- 他世代の件数を取得
		SELECT COUNT(*) INTO i
		  FROM TP756
		  WHERE BKNCD = w_BKNCD
		    AND SEDAI != p_sedai_b;
		-- 他世代が存在する場合
		IF i > 1 THEN
			p_naiyo := SUBSTR(p_dyset_b, 5, 2) || '/' || SUBSTR(p_dyset_b, 7, 2) || '追加';
		END IF;
	ELSE
		-- 新規改造区分又は仕様が異なっている場合
		IF p_kubun_b || p_siyo_b != p_kubun || p_siyo THEN
			p_naiyo := SUBSTR(p_dyset, 5, 2) || '/' || SUBSTR(p_dyset, 7, 2) || '変更';
		END IF;
	END IF;

	-- 作業内容を戻り値にする
	RETURN p_naiyo;

EXCEPTION
	WHEN OTHERS THEN
		RETURN NULL;
END TP756_NAIYO;
/
CREATE OR REPLACE FUNCTION TP756_SIYONM (
	  w_BKNCD	VARCHAR2	default null		-- 物件コード
	, w_AREA	VARCHAR2	default null		-- エリア
	, w_PWBS	VARCHAR2	default null		-- PWBS
	, w_SUB		VARCHAR2	default null		-- SUB
) RETURN VARCHAR2 IS

	p_siyonm	varchar2(200) := null;	-- 仕様名称
	p_kubun		TP756.KUBUN%type;		-- 新規改造区分
	p_siyo		TP756.SIYO%type;		-- 仕様
	p_sudai		TP756.SUDAI%type;		-- 台数
	p_tndai		TP756.TNDAI%type;		-- 台数単位
	p_pgset		TP756.PGSET%type;		-- 作成PG

BEGIN

	FOR vRec IN
	  ( SELECT *
	      FROM TP756
	      WHERE BKNCD = w_BKNCD
	        AND AREA = w_AREA
	        AND PWBS = w_PWBS
	        AND SUB = w_SUB
	      ORDER BY SEDAI )
	LOOP
		p_kubun := vRec.KUBUN;
		p_siyo := vRec.SIYO;
		p_sudai := vRec.SUDAI;
		p_tndai := vRec.TNDAI;
		p_pgset := vRec.PGSET;
	END LOOP;

	-- 仕様をセット
	p_siyonm := p_siyo;

	-- 新PMS移行データ
	IF p_pgset != 'TQP19027' THEN
		-- 改造の場合
		IF p_kubun = '02' THEN
			p_siyonm := p_siyonm || ' 改造';
		END IF;
		-- 台数＆台数単位
		IF p_sudai IS NOT NULL THEN
			p_siyonm := p_siyonm || ' * ' || TO_CHAR(p_sudai) || p_tndai;
		END IF;
	END IF;

	-- 仕様名称を戻り値にする
	RETURN p_siyonm;

EXCEPTION
	WHEN OTHERS THEN
		RETURN NULL;
END TP756_SIYONM;
/
CREATE OR REPLACE FUNCTION TP756_TOKKI (
	  w_BKNCD	VARCHAR2	default null		-- 物件コード
	, w_AREA	VARCHAR2	default null		-- エリア
	, w_PWBS	VARCHAR2	default null		-- PWBS
	, w_SUB		VARCHAR2	default null		-- SUB
) RETURN VARCHAR2 IS

	p_tokki		varchar2(50) := null;	-- 特記事項
	p_sudai		TP756.SUDAI%type := 0;	-- 台数
	p_sudai_b	TP756.SUDAI%type := 0;	-- 台数(前)
	i INT := 0;

BEGIN
	FOR vRec IN
	  ( SELECT SUDAI
	      FROM TP756
	      WHERE BKNCD = w_BKNCD
	        AND AREA = w_AREA
	        AND PWBS = w_PWBS
	        AND SUB = w_SUB
	      ORDER BY SEDAI )
	LOOP
		i := i + 1;
		IF i = 1 THEN
			p_sudai_b := vRec.SUDAI;
		ELSE
			p_sudai := vRec.SUDAI;
		END IF;
	END LOOP;

	IF i > 1 AND p_sudai_b != p_sudai THEN
		p_tokki := '台数 ' || TO_CHAR(p_sudai_b) || '->' || TO_CHAR(p_sudai);
	END IF;

	-- 特記事項を戻り値にする
	RETURN p_tokki;

EXCEPTION
	WHEN OTHERS THEN
		RETURN NULL;
END TP756_TOKKI;
