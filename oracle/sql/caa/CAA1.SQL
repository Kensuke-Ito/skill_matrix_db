CREATE OR REPLACE VIEW CBV_USRINF
    (USRSEQ,USRKBN,MAIL,USRNM,SYKIID,SYKMID,DELFLG,DPMTNM,DPMTCD,USRID,
    USREPCD)
AS
SELECT
 USR.USRSEQ AS USRSEQ,
 USR.USRKBN AS USRKBN,
 USR.MAIL AS MAIL,
 USR.USRNM AS USRNM,
 USR.SYKIID AS SYKIID,
 USR.SYKMID AS SYKMID,
 USR.DELFLG AS DELFLG,
 DPMT.VAL AS DPMTNM,
 DPCD.VAL AS DPMTCD,
 EPCD.VAL AS USRID,
 EPCD.USREPCD AS USREPCD  -- 2025/09/04 社員番号(USREPCD)追加
FROM 
 CB.CBM_USR USR
 LEFT JOIN (
  SELECT
   USRSEQ,
   VAL
  FROM
   CB.CBT_USRATTRINF
  WHERE
   KEY = 'CBUA_USR_DPMT'
 ) DPMT ON DPMT.USRSEQ = USR.USRSEQ
 LEFT JOIN (
  SELECT
   USRSEQ,
   VAL
  FROM
   CB.CBT_USRATTRINF
  WHERE
   KEY = 'CBUA_USR_DPCD'
 ) DPCD ON DPCD.USRSEQ = USR.USRSEQ
 LEFT JOIN (
  SELECT
   USRSEQ,
   VAL AS USREPCD,  -- 2025/09/04 社員番号(USREPCD)追加
   (CASE WHEN VAL IS NULL THEN NULL
   ELSE 'C' || VAL
   END) AS VAL
  FROM
   CB.CBT_USRATTRINF
  WHERE
   KEY = 'CBUA_USR_EPCD'
 ) EPCD ON EPCD.USRSEQ = USR.USRSEQ
WITH READ ONLY
/
CREATE OR REPLACE VIEW CBV_USRINF2
    (USRSEQ,USRKBN,USRKBNNM,MAIL,USRNM,SYKIID,SYKMID,DELFLG,LGINID,LANG)
AS
SELECT 
 USR.USRSEQ AS USRSEQ,
 USR.USRKBN AS USRKBN,
 USRKBN.USRKBNNM AS USRKBNNM,
 USR.MAIL AS MAIL,
 USR.USRNM AS USRNM,
 USR.SYKIID AS SYKIID,
 USR.SYKMID AS SYKMID,
 USR.DELFLG AS DELFLG,
 USRLGIN.LGINID AS LGINID,
 CASE WHEN CSTMINF.VAL is NULL OR CSTMINF.VAL = '' THEN 'ja' ELSE CSTMINF.VAL END AS LANG
FROM 
 CB.CBM_USR USR
 LEFT JOIN (
  SELECT
   USRKBN,
   USRKBNNM
  FROM
   CB.CBM_USRKBN
 ) USRKBN ON USR.USRKBN = USRKBN.USRKBN
 LEFT JOIN (
  SELECT
   USRSEQ,
   LGINID
  FROM
   CB.CBM_LGIN
 ) USRLGIN ON USR.USRSEQ = USRLGIN.USRSEQ
 LEFT JOIN (
  SELECT
   LGINID,
   VAL
  FROM
   CB.CBT_CSTMINF
  WHERE
   KEY = 'CBUA_USR_LANG'
 ) CSTMINF ON USRLGIN.LGINID = CSTMINF.LGINID
 WITH READ ONLY
/
CREATE OR REPLACE VIEW CBV_USRSEARCH
    (USRSEQ,VALUE)
AS
SELECT
 USR.USRSEQ AS USRSEQ,
 NVL2(LSTNM.VAL, LSTNM.VAL || '|', '') ||
 NVL2(MDLNM.VAL, MDLNM.VAL || '|', '') ||
 NVL2(FSTNM.VAL, FSTNM.VAL || '|', '') ||
 NVL2(LSTNMKN.VAL, LSTNMKN.VAL || '|', '') ||
 NVL2(MDLNMKN.VAL, MDLNMKN.VAL || '|', '') ||
 NVL2(FSTNMKN.VAL, FSTNMKN.VAL || '|', '') ||
 NVL2(EPCD.VAL, EPCD.VAL, '') AS VALUE
FROM
 CB.CBM_USR USR
 LEFT JOIN (SELECT USRSEQ, VAL FROM CB.CBT_USRATTRINF WHERE KEY = 'CBUA_USR_LSTNM') LSTNM ON USR.USRSEQ = LSTNM.USRSEQ
 LEFT JOIN (SELECT USRSEQ, VAL FROM CB.CBT_USRATTRINF WHERE KEY = 'CBUA_USR_MDLNM') MDLNM ON USR.USRSEQ = MDLNM.USRSEQ
 LEFT JOIN (SELECT USRSEQ, VAL FROM CB.CBT_USRATTRINF WHERE KEY = 'CBUA_USR_FSTNM') FSTNM ON USR.USRSEQ = FSTNM.USRSEQ
 LEFT JOIN (SELECT USRSEQ, VAL FROM CB.CBT_USRATTRINF WHERE KEY = 'CBUA_USR_LSTNMKN') LSTNMKN ON USR.USRSEQ = LSTNMKN.USRSEQ
 LEFT JOIN (SELECT USRSEQ, VAL FROM CB.CBT_USRATTRINF WHERE KEY = 'CBUA_USR_MDLNMKN') MDLNMKN ON USR.USRSEQ = MDLNMKN.USRSEQ
 LEFT JOIN (SELECT USRSEQ, VAL FROM CB.CBT_USRATTRINF WHERE KEY = 'CBUA_USR_FSTNMKN') FSTNMKN ON USR.USRSEQ = FSTNMKN.USRSEQ
 LEFT JOIN (SELECT USRSEQ, VAL FROM CB.CBT_USRATTRINF WHERE KEY = 'CBUA_USR_EPCD') EPCD ON USR.USRSEQ = EPCD.USRSEQ
/
CREATE OR REPLACE VIEW SAKU_USR
    (USERID,SYAIN,BUKA,SYAINK,SYOKUSYU,SYOKUSEI,NMSYA)
AS
SELECT 
	"USERID"
	,"SYAIN"
	,"BUKA"
	,"SYAINK"
	,"SYOKUSYU"
	,"SYOKUSEI"
	,"NMSYA"
	
FROM(

	SELECT
		MST_ID.id AS USERID,
		MST_ID.SYAIN,
		MST_SYAIN.HBUKA AS BUKA,
		SYAINK,
		SYOKUSYU,
		SYOKUSEI,
		MST_SYAIN.SEI || MST_SYAIN.MEI AS NMSYA 

	FROM
		MST_ID
	LEFT JOIN
		MST_SYAIN
	ON 
		MST_ID.SYAIN = MST_SYAIN.SYAIN
	WHERE
		MST_ID.TAISYADT IS NULL
	)
