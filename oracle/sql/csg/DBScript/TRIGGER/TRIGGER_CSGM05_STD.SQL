CREATE OR REPLACE TRIGGER CSG.TRIGGER_CSGM05_STD
BEFORE INSERT OR UPDATE 
ON CSG.CSGM05
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW 
BEGIN
    IF INSERTING THEN
        /*
        :NEW.SYAIN := GET_PARTNER_SYAIN(CSGM05_SEQNO.nextval);
        */
        :NEW.DYSET := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
        :NEW.DYUPD := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
    ELSE
        :NEW.DYUPD := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
    END IF;
END;

/
