CREATE OR REPLACE TRIGGER CSG.TRIGGER_CSGM16_STD
BEFORE INSERT OR UPDATE 
ON CSG.CSGM16
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW 
BEGIN
    IF INSERTING THEN
        /*
        :NEW.WRK_CD := CSGM16_SEQNO.nextval;
        */
        :NEW.DYSET := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
        :NEW.DYUPD := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
    ELSE
        :NEW.DYUPD := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
    END IF;
END;

/
