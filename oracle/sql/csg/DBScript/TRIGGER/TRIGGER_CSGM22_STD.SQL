CREATE OR REPLACE TRIGGER CSG.TRIGGER_CSGM22_STD
BEFORE INSERT OR UPDATE 
ON CSG.CSGM22
REFERENCING OLD AS OLD NEW AS NEW
FOR EACH ROW 
BEGIN
    IF INSERTING THEN
        /*
        :NEW.LV_SEQNO := CSGM22_SEQNO.nextval;
        */
        :NEW.DYSET := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
        :NEW.DYUPD := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
    ELSE
        :NEW.DYUPD := TO_CHAR(sysdate,'YYYYMMDDHH24MISS');
    END IF;
END;

/
